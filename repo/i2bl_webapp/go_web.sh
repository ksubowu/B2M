#!/usr/bin/env bash
# B2M publication modification: use the active Python environment or PYTHON_BIN.
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd)"
PYTHON_BIN="${PYTHON_BIN:-python}"
WEBAPP_DATA="${WEBAPP_DATA:-$PROJECT_ROOT/webapp_data}"
"$PYTHON_BIN" "$PROJECT_ROOT/scripts/restore_webapp_examples.py" --storage "$WEBAPP_DATA"
export I2BL_RESULTS_DATA_DIR="${I2BL_RESULTS_DATA_DIR:-$WEBAPP_DATA/results_data}"
export I2BL_FIXED_DATA_DIR="${I2BL_FIXED_DATA_DIR:-$WEBAPP_DATA/fixed_data}"
export I2BL_TRAINING_PAIRS_DIR="${I2BL_TRAINING_PAIRS_DIR:-$I2BL_FIXED_DATA_DIR/training_pairs}"
export I2BL_EXAMPLES_DIR="${I2BL_EXAMPLES_DIR:-$WEBAPP_DATA/examples}"
export I2BL_PASTED_EXAMPLES_DIR="${I2BL_PASTED_EXAMPLES_DIR:-$WEBAPP_DATA/pasted_examples}"
export I2BL_CLASSES="${I2BL_CLASSES:-$WEBAPP_DATA/classes.json}"
export I2BL_CONFIG="${I2BL_CONFIG:-$PROJECT_ROOT/config/train_mp123_full.yml}"
export I2BL_CHECKPOINT="${I2BL_CHECKPOINT:-$PROJECT_ROOT/runs/human_joint_full_20261027/best_base.pth}"
export I2BL_INFERENCE_PROFILE="${I2BL_INFERENCE_PROFILE:-legacy}"
export I2BL_KETCHER_DIR="${I2BL_KETCHER_DIR:-$SCRIPT_DIR/ketcher}"
export EASYOCR_MODEL_DIR="${EASYOCR_MODEL_DIR:-$WEBAPP_DATA/ocr_models}"
export I2BL_OCR_BACKEND="${I2BL_OCR_BACKEND:-easyocr}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-6}"
export OMP_NUM_THREADS="${OMP_NUM_THREADS:-2}"
export OPENBLAS_NUM_THREADS="${OPENBLAS_NUM_THREADS:-2}"
cd "$SCRIPT_DIR"
exec "$PYTHON_BIN" -m uvicorn webapp:app --host "${WEBAPP_HOST:-0.0.0.0}" --port "${WEBAPP_PORT:-2861}"
